import type { SeedQuestion as Question, Difficulty, QuestionPhase, QuestionType } from '../../types';

// ============================================================
// SUROJ × BE10X — DEPARTMENT PRACTICAL APPLICATION SUPPLEMENT
// Additional department-specific practical items so every
// department has a deep PRE and POST pool.
// ============================================================

type Opt = [string, string, string, string];

function mcq(
  id: string, dept: string, phase: QuestionPhase, difficulty: Difficulty,
  question_text: string, options: Opt, correct: 'a' | 'b' | 'c' | 'd', explanation?: string,
): Partial<Question> {
  return {
    id, department_id: dept, question_type: 'mcq', competency: 'department_application', difficulty,
    question_text, max_marks: 2, assessment_phase: phase, correct_answer: correct, explanation,
    options: options.map((text, i) => ({ id: 'abcd'[i], text })),
  };
}

function open(
  id: string, dept: string, phase: QuestionPhase, type: QuestionType, difficulty: Difficulty,
  marks: number, question_text: string, rubric: string, scenario_text?: string,
): Partial<Question> {
  return {
    id, department_id: dept, question_type: type, competency: 'department_application', difficulty,
    question_text, scenario_text, max_marks: marks, rubric, assessment_phase: phase,
  };
}

